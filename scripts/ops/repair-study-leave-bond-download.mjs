// Run from apps/web with --env-file=.env.local; pass --apply to repair.
import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const require = createRequire(new URL('../../apps/web/package.json', import.meta.url));
const { createClient } = require('@supabase/supabase-js');
const { BlobServiceClient } = require('@azure/storage-blob');
const key = Object.keys(process.env).find(k => k.replace(/^\uFEFF/, '') === 'NEXT_PUBLIC_SUPABASE_URL');
const db = createClient(process.env[key], process.env.SUPABASE_SERVICE_ROLE_KEY);
const id = 'a28cdcd7-d795-4af5-99f3-ce3e337d1130';
const filename = 'kZgH0TYEk8hkvrox6HERqVyZ1MWKoHdW24Wn6NXE.pdf';
const originalPath = `legacy-pending/downloads/20/${filename}`;
const container = process.env.NEXT_PUBLIC_AZURE_STORAGE_CONTAINER || process.env.AZURE_STORAGE_CONTAINER || 'ccshaucontainer';
const blobPath = `downloads/${id}/${filename}`;
const repairedPath = `${container}/${blobPath}`;
const bytes = await readFile(`C:/Jatin/Projects/CCHAU_mysql/uploads/uploads/downloads-pdf/${filename}`);
if (bytes.subarray(0, 5).toString() !== '%PDF-') throw new Error('Original is not a PDF');
const { data: row, error } = await db.from('ccshau_downloads').select('id,title_en,file_path').eq('id', id).single();
if (error) throw error;
if (![originalPath, repairedPath].includes(row.file_path)) throw new Error('Record changed; refusing overwrite');
console.log(JSON.stringify({ title: row.title_en, currentPath: row.file_path, repairedPath, bytes: bytes.length }));
if (!process.argv.includes('--apply')) process.exit(0);
const blob = BlobServiceClient.fromConnectionString(process.env.AZURE_STORAGE_CONNECTION_STRING).getContainerClient(container).getBlockBlobClient(blobPath);
if (!(await blob.exists())) await blob.uploadData(bytes, { blobHTTPHeaders: { blobContentType: 'application/pdf' } });
const hash = data => createHash('sha256').update(data).digest('hex');
if (hash(await blob.downloadToBuffer()) !== hash(bytes)) throw new Error('Uploaded PDF differs from original');
const { data: updated, error: updateError } = await db.from('ccshau_downloads').update({ file_path: repairedPath, file_name: filename, file_size: bytes.length, mime_type: 'application/pdf' }).eq('id', id).eq('file_path', row.file_path).select('id,file_path').single();
if (updateError) throw updateError;
console.log(JSON.stringify({ repaired: updated, verifiedSha256: hash(bytes) }));
